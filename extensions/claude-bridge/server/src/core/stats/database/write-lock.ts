// Единственный писатель статистической DuckDB.
//
// Зачем. DuckDB роняет ВЕСЬ процесс, если у транзакции не удался COMMIT и
// откат наткнулся на индекс: `duckdb::FatalException` в `RevertCommit` →
// `terminate called`, Node это не перехватывает. Ровно так упал сервер
// 6.3.131: два воркера сборщика JSONL писали в `jsonl_events` с разных
// соединений, второй COMMIT получил дубликат первичного ключа, откат упёрся в
// тот же ключ. UPDATE по индексированной колонке DuckDB исполняет как
// delete+insert, поэтому в откат попадает и он.
//
// Единственный способ сделать это невозможным — не иметь двух одновременных
// пишущих транзакций: тогда COMMIT не с кем конфликтовать, а конфликт внутри
// одной транзакции снимается дедупликацией пачки до вставки
// (`jsonl-batch.ts`). Чтение при этом остаётся параллельным — MVCC.
//
// Очередь — цепочка промисов: каждый писатель ждёт хвост и становится новым
// хвостом. Отказ писателя хвост не рвёт: следующий всё равно получит ход.

let tail: Promise<void> = Promise.resolve()
let depth = 0

/** Выполнить пишущую операцию строго после всех ранее поставленных. */
export function withStatsWrite<T>(fn: () => Promise<T>): Promise<T> {
  depth++
  const run = tail.then(fn)
  tail = run.then(
    () => { depth-- },
    () => { depth-- },
  )
  return run
}

/** Сколько писателей ждут или исполняются — для диагностики и тестов. */
export function statsWriteDepth(): number {
  return depth
}
