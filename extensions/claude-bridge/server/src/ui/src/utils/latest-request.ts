// Владение запросом: публиковать ответ имеет право только САМЫЙ ПОСЛЕДНИЙ
// запрос (INC-2026-0015).
//
// График использования держал выбранный период, данные и признак загрузки в
// независимых сигналах и публиковал КАЖДЫЙ ответ безусловно. Быстрое
// переключение периода давало ярлык «Yearly» над более старым дневным ответом,
// пустые или неверные значения и погасший индикатор загрузки при ещё идущем
// запросе: порядок ответов сети не совпадает с порядком запросов.
//
// Отмены у клиента нет, и вводить её ради этого не требуется — достаточно не
// принимать во внимание устаревший ответ.

export interface RequestOwner {
  /** Начать запрос и получить его метку. Все прежние метки устаревают. */
  begin: () => number
  /** Эта метка всё ещё принадлежит последнему запросу? */
  isCurrent: (token: number) => boolean
}

export function createRequestOwner(): RequestOwner {
  let generation = 0
  return {
    begin: () => (generation += 1),
    isCurrent: (token: number) => token === generation,
  }
}
