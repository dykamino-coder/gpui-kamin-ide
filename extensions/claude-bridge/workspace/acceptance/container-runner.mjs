// Host orchestration only: this file never imports Playwright or launches a browser.
import { mkdir, realpath } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { randomUUID } from 'node:crypto'
import path from 'node:path'
import { parseArgs } from 'node:util'
import { spawn } from 'node:child_process'
import { command } from './resources.mjs'

const { values } = parseArgs({ options: {
  mode: { type: 'string', default: 'live' }, 'report-dir': { type: 'string' },
  image: { type: 'string', default: 'localhost/bridgeweb-acc-workspace:local' },
  'runner-image': { type: 'string', default: 'localhost/bridgeweb-acc-playwright:local' },
  'podman-socket': { type: 'string', default: '/run/podman/podman.sock' },
  strict: { type: 'boolean', default: false },
} })
if (!values['report-dir'] || !['live', 'fixture', 'credentials'].includes(values.mode)) throw new Error('Specify --report-dir outside the checkout and --mode live|fixture|credentials')
if (!/^\/run\/(user\/\d+\/)?podman\/podman\.sock$/.test(values['podman-socket'])) throw new Error('Expected Podman VM socket path')
const repo = await realpath(fileURLToPath(new URL('../../../../', import.meta.url)))
await mkdir(path.resolve(values['report-dir']), { recursive: true })
const reports = await realpath(path.resolve(values['report-dir']))
const relative = path.relative(repo, reports)
if (!relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative)) throw new Error('Report directory must be outside checkout')
const source = (await command('git', ['-C', repo, 'rev-parse', 'HEAD'])).trim()
const dirty = !!(await command('git', ['-C', repo, 'status', '--porcelain'])).trim()
const name = `bridgeweb-acc-browser-${randomUUID()}`
// In the Podman VM the supplied server publishes on VM loopback. Pin this name
// to that interface rather than the Windows gateway generated by Podman.
const args = ['run', '--name', name, '--network', 'host', '--add-host', 'host.containers.internal:127.0.0.1', '--ipc', 'private', '--shm-size', '1g',
  '--mount', `type=bind,source=${repo},destination=/source,ro=true`,
  '-e', 'BRIDGEWEB_ACC_CONTAINER=1', '-e', `BRIDGEWEB_ACC_SOURCE=${source}`, '-e', `BRIDGEWEB_ACC_SOURCE_DIRTY=${dirty ? '1' : '0'}`]
if (values.mode !== 'fixture') args.push('--mount', `type=bind,source=${values['podman-socket']},destination=/run/bridgeweb-acc-podman.sock`,
  '-e', 'CONTAINER_HOST=unix:///run/bridgeweb-acc-podman.sock')
args.push(values['runner-image'], values.mode)
if (values.mode !== 'fixture') args.push('--image', values.image, ...(values.strict ? ['--strict'] : []))
let started = false
try {
  const child = spawn('podman', args, { windowsHide: true, stdio: 'inherit' })
  started = true
  const code = await new Promise((resolve, reject) => { child.once('error', reject); child.once('close', resolve) })
  // Retain only sanitized summaries (live) or synthetic fixture TAP (fixture).
  await command('podman', ['cp', `${name}:/reports/.`, reports])
  process.exitCode = code ?? 1
} finally {
  if (started) await command('podman', ['rm', name])
}
