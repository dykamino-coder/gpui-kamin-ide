#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_outer_and_customize_events() {
        assert_eq!(name(&ShellEvent::TogglePalette), "host/TogglePalette");
        assert_eq!(
            name(&ShellEvent::Cz(CzEvent::ExtensionsStatus(String::new()))),
            "host/Cz/ExtensionsStatus"
        );
    }
}
