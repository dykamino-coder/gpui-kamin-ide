//! Контракты чтения `Option<Len>` в точки по именам: что считается нулём, что
//! непроходимо, что теряется. Одно короткое `px` скрывало три разных правила,
//! и перенос вызова между модулями молча менял смысл.
//!
//! Перевод с базой долей и контекстом шрифта — `Len::to_px`
//! (`style::computed::resolve::len_px`); здесь только правила без контекста.

use super::Len;

/// Только явные точки: всё прочее (включая отсутствие значения и `auto`) —
/// `None`. Гейт «размер задан в точках».
pub fn px_strict(l: Option<Len>) -> Option<f32> {
    match l {
        Some(Len::Px(v)) => Some(v),
        _ => None,
    }
}

/// Отсутствующее значение — ноль, `auto` НЕПРОХОДИМО (`None`): сторона
/// коробки, где `auto` меняет смысл (поле прижимает к краю, ширина
/// shrink-to-fit), а незаданная сторона равна нулю.
pub fn px_missing_zero(l: Option<Len>) -> Option<f32> {
    match l {
        None => Some(0.0),
        Some(Len::Px(v)) => Some(v),
        _ => None,
    }
}

/// Отсутствующее значение и `auto` — ноль, прочие неточечные длины
/// непроходимы: поля и отступы в оценках фрагментации, где `auto` ничего не
/// добавляет к размеру.
pub fn px_auto_zero(l: Option<Len>) -> Option<f32> {
    match l {
        None | Some(Len::Auto) => Some(0.0),
        Some(Len::Px(v)) => Some(v),
        _ => None,
    }
}

/// Точки или ноль С ПОТЕРЕЙ: доля, шрифтовая единица и `auto` читаются
/// нулём. Законно только там, где неточечное значение уже решено раньше или
/// по смыслу равно нулю; каждый вызов на это рассчитывает осознанно.
pub fn px_lossy_zero(l: Option<Len>) -> f32 {
    match l {
        Some(Len::Px(v)) => v,
        _ => 0.0,
    }
}
