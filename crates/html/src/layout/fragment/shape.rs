//! Измеренная геометрия коробки и допустимые границы её фрагментов.

/// Размеры в CSS px; смещения отсчитываются от начала измеряемой коробки
/// в системе координат `shape_full`, внешние поля в них не входят.
#[derive(Clone, Debug, Default, PartialEq)]
pub(crate) struct Shape {
    /// Измеренная протяжённость коробки и её потока без внешних полей.
    pub(crate) height: f32,
    pub(crate) margin_top: f32,
    pub(crate) margin_bottom: f32,
    /// Минимальная помещающаяся высота и начало следующего фрагмента.
    pub(crate) cuts: Vec<(f32, f32)>,
    /// Смещения принудительных разрывов.
    pub(crate) forced: Vec<f32>,
    /// Диапазоны монолитного содержимого, не допускающие разрыв внутри.
    pub(crate) solid: Vec<(f32, f32)>,
}
