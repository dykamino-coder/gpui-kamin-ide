//! Числовые допуски и пороги округления — один реестр на crate.
//!
//! Константы названы по природе величины и контракту: сравнение
//! координат раскладки, пригодность кандидата фрагментации, геометрия
//! линейки промежутков, вырожденность плоскости гомографии, близость цвета к
//! краю охвата, привязка к пикселю и граница проекции. Величины РАЗНЫЕ
//! намеренно — у каждой своя причина (ниже), и
//! общий «эпсилон» на всех дал бы либо слипание дорожек, либо ложные
//! переносы. Новый допуск заводится здесь с объяснением, не литералом на
//! месте.

/// Допуск сравнения координат и размеров раскладки в точках CSS.
///
/// Накопленная ошибка f32 при сложении координат на масштабе ~10³ px — порядка
/// 10⁻⁴; сотая точки её перекрывает и остаётся ниже любого кванта растра при
/// масштабе экрана ≤ 4. Им меряются полосы флоатов (флоат ровно по ширине
/// контейнера не должен уезжать вниз), края фрагментов, таблиц и страниц.
pub const COORD_EPS: f32 = 0.01;

/// Допуск «кандидат фрагментации помещается» (css-break-3 §4.1).
///
/// Высоты коробок приходят от раскладки, округлённой до целой точки (taffy),
/// а границы фрагментаторов — дробные. Выход за край меньше половины точки —
/// это ровно шаг округления, а не настоящий перелив; меньший допуск рвал
/// строки, которые браузер оставляет на странице.
pub const FRAGMENT_FIT_EPS: f32 = 0.5;

/// Допуск геометрии линеек промежутков (css-gaps-1): край элемента против
/// дорожки.
///
/// Края элементов — округлённые раскладкой целые точки, позиции дорожек —
/// дробные (доля свободного места). 0.35 больше половины суммарной ошибки
/// округления двух сторон на масштабе 1.0, но меньше 0.5: соседние дорожки
/// шириной в точку не слипаются в одну.
pub const GAP_RULE_EPS: f32 = 0.35;

/// Порог вырожденности плоскости 3D-преобразования: `|det| < EPS` — плоскость
/// за глазом или ребром, аффинной касательной у неё нет.
///
/// Измеряется в единицах матрицы (безразмерно), а не в точках, поэтому
/// порог на три порядка мельче координатных.
pub const PLANE_SINGULAR_EPS: f32 = 1e-5;

/// «Почти в охвате»: компонент sRGB в `[-SLACK, 1 + SLACK]` зажимается, а не
/// отображается охватно.
///
/// Путь профиль → D50 → D65 → sRGB с округлением колорантов s15Fixed16
/// выводит чистые цвета чуть за край (`0000ff` → (−0.01, 0.003, 1.0x));
/// охватное отображение (OKLCh) по такой мелочи сдвигало тон
/// (`order-of-images`: 0033e6 вместо 0000ff).
pub const GAMUT_SLACK: f32 = 0.02;

/// Точность текстовых расстояний в точках CSS: продвижение табуляции,
/// повторный замер атома и незначительный сдвиг/размер прогона.
/// Тысячная точки сохраняет точность набора; COORD_EPS здесь слишком груб.
pub const TEXT_COORD_EPS: f32 = 1e-3;

/// Близость безразмерного параметра суперэллипса K к круглому углу K=1.
/// Растр и контур выбирают прежнюю круглую ветвь с этим же порогом.
pub const CORNER_CURVATURE_EPS: f32 = 1e-3;

/// Допуск размещения и совпадения строк при clamp/ellipsis в точках CSS.
/// Сопоставляет дробные метрики текста с округлёнными краями коробок;
/// это отдельный контракт от пригодности фрагмента страницы/колонки.
pub const LINE_FIT_EPS: f32 = 0.5;

/// Совпадение краёв краски в точках CSS: скругление плитки у края области
/// и объединение соседних срезов табличной рамки в пределах полточки.
pub const PAINT_EDGE_EPS: f32 = 0.5;

/// Неразличимый остаток используемой ширины таблицы в точках CSS:
/// нулевая свободная ширина и превышение суммы колонок над заданной.
pub const TABLE_SIZE_EPS: f32 = 0.5;

/// Безразмерный допуск количества плиток перед округлением вниз;
/// не применяется к длине плитки или координатам её краёв.
pub const TILE_COUNT_EPS: f32 = 1e-3;

/// Незначимое отличие безразмерного множителя text-fit от единицы.
pub const TEXT_FIT_SCALE_EPS: f32 = 1e-3;

/// Шум линейных коэффициентов матрицы около целого (безразмерно).
pub const TRANSFORM_LINEAR_EPS: f32 = 1e-5;

/// Шум переноса растровой карты около целого, в точках CSS.
/// Применяется только при целочисленной линейной части преобразования.
pub const TRANSFORM_TRANSLATION_EPS: f32 = 1e-3;

/// Максимальная поправка начала вертикального текста в точках CSS:
/// сохраняет фазу округления, не позволяя ей сдвинуть рамку на целую точку.
pub const TEXT_ORIGIN_SNAP_EPS: f32 = 0.5;

/// Допуск продвижения сформированного пробельного прогона в точках CSS:
/// меньшую разницу между целевым и измеренным пробелом не компенсируем.
pub const SHAPED_ADVANCE_EPS: f32 = 0.5;

/// Смещение перед floor при привязке повёрнутого текста к физическому
/// пикселю; убирает отрицательный шум у целой границы, не сравнивает длины.
pub const RASTER_FLOOR_BIAS: f32 = 1e-3;

/// Нижняя видимая граница однородной координаты w при проекции коробки.
/// Безразмерный near-plane guard, не допуск определителя матрицы.
pub const HOMOGENEOUS_CLIP_MIN: f32 = 1e-3;
